type Inputs = {
  email: string;
  password: string;
  company: string;
  providerToken: string;
  provider: string;
};
export function Register() {
  const getQuery = useSearchParams();
  const fetch = useFetch();
  const provider = getQuery?.get('provider')?.toUpperCase() || '';
  const code = getQuery?.get('code') || '';
  const state = getQuery?.get('state') || '';
  const isCallback = ['provider', 'code', 'state', 'error'].some((key) =>
    getQuery?.has(key)
  );
  const validCallback =
    !!code &&
    !getQuery?.has('error') &&
    ['GOOGLE', 'GITHUB', 'APPLE', 'GENERIC', 'FARCASTER', 'WALLET'].includes(
      provider
    );
  const key = JSON.stringify([provider, code, state, validCallback]);
  type CallbackResult = {
    key: string;
    status: 'register' | 'private' | 'error' | 'login';
    token?: string;
  };
  const [result, setResult] = useState<CallbackResult>();
  // Reuse the exchange during effect replay: authorization codes are single-use.
  const attempt = useRef<
    { key: string; promise: Promise<CallbackResult> } | undefined
  >(undefined);
  useEffect(() => {
    if (!isCallback || !validCallback) {
      return;
    }
    let active = true;
    if (attempt.current?.key !== key) {
      attempt.current = {
        key,
        promise: (async (): Promise<CallbackResult> => {
          try {
            const response = await fetch(`/auth/oauth/${provider}/exists`, {
              method: 'POST',
              body: JSON.stringify({ code, state }),
            });
            const body = await response.json();
            if (!response.ok) {
              return {
                key,
                status:
                  response.status === 403 &&
                  body?.code === 'registration_disabled'
                    ? 'private'
                    : 'error',
              };
            }
            // The shared fetch wrapper already handles cookies and reload headers.
            if (body?.login === true) {
              return { key, status: 'login' };
            }
            if (typeof body?.token === 'string' && body.token.trim()) {
              return { key, status: 'register', token: body.token };
            }
          } catch {
            // Never render provider responses, authorization codes or exception text.
          }
          return { key, status: 'error' };
        })(),
      };
    }
    void attempt.current.promise.then((next) => {
      if (active) {
        setResult(next);
      }
    });
    return () => {
      active = false;
    };
  }, [fetch, key, provider, code, state, isCallback, validCallback]);
  if (!isCallback) {
    return <RegisterAfter token="" provider="LOCAL" />;
  }
  const current = result?.key === key ? result : undefined;
  if (validCallback && !current) {
    return <LoadingComponent />;
  }
  if (current?.status === 'register') {
    return <RegisterAfter token={current.token!} provider={provider} />;
  }
  return (
    <div className="flex flex-col gap-4 text-sm">
      <p role="status">
        {current?.status === 'private'
          ? 'This publisher is private. Contact your administrator.'
          : current?.status === 'login'
          ? 'Signing you in. If you are not redirected, return to sign in.'
          : 'Unable to sign in. Please return to sign in and try again.'}
      </p>
      <Link href="/auth/login" className="underline cursor-pointer">
        Return to sign in
      </Link>
    </div>
  );
}
function getHelpfulReasonForRegistrationFailure(httpCode: number) {
  switch (httpCode) {
    case 400:
      return 'Email already exists';
    case 404:
      return 'Your browser got a 404 when trying to contact the API, the most likely reasons for this are the NEXT_PUBLIC_BACKEND_URL is set incorrectly, or the backend is not running.';
  }
  return 'Unhandled error: ' + httpCode;
}
export function RegisterAfter({
  token,
  provider,
}: {
  token: string;
  provider: string;
}) {
  const t = useT();
  const {
    isGeneral,
    genericOauth,
    neynarClientId,
    appleClientId,
    billingEnabled,
  } = useVariables();
  const [loading, setLoading] = useState(false);
  const router = useRouter();
  const fireEvents = useFireEvents();
  const track = useTrack();
  const [datafast_visitor_id] = useCookie('datafast_visitor_id');
  const isAfterProvider = useMemo(() => {
    return !!token && !!provider;
  }, [token, provider]);
  const resolver = useMemo(() => {
    return classValidatorResolver(CreateOrgUserDto);
  }, []);
  const form = useForm<Inputs>({
    resolver,
    defaultValues: {
      providerToken: token,
      provider: provider,
    },
  });
  const fetchData = useFetch();
  const onSubmit: SubmitHandler<Inputs> = async (data) => {
    setLoading(true);
    await fetchData('/auth/register', {
      method: 'POST',
      body: JSON.stringify({
        ...data,
        datafast_visitor_id,
      }),
    })
      .then(async (response) => {
        setLoading(false);
        if (response.status === 200) {
          fireEvents('register');
          return track(TrackEnum.CompleteRegistration).then(() => {
            if (response.headers.get('activate') === 'true') {
              router.push('/auth/activate');
            } else {
              router.push('/auth/login');
            }
          });
        } else {
          form.setError('email', {
            message: await response.text(),
          });
        }
      })
      .catch((e) => {
        form.setError('email', {
          message:
            'General error: ' +
            e.toString() +
            '. Please check your browser console.',
        });
      });
  };
  return (
    <FormProvider {...form}>
      <form className="flex-1 flex" onSubmit={form.handleSubmit(onSubmit)}>
        <div className="flex flex-col flex-1">
          <div>
            <h1 className="text-[40px] font-[500] -tracking-[0.8px] text-start cursor-pointer">
              {t('sign_up', 'Sign Up')}
            </h1>
          </div>
          <div className="text-[14px] mt-[32px] mb-[12px]">
            {t('continue_with', 'Continue With')}
          </div>
          <div className="flex flex-col text-[14px]">
            {!isAfterProvider &&
              (!isGeneral ? (
                <GithubProvider />
              ) : (
                <div className="gap-[8px] flex">
                  {genericOauth && isGeneral ? (
                    <OauthProvider />
                  ) : (
                    <GoogleProvider />
                  )}
                  {!!appleClientId && <AppleProvider />}
                  {!!neynarClientId && <FarcasterProvider />}
                  {billingEnabled && <WalletProvider />}
                </div>
              ))}
            {!isAfterProvider && (
              <div className="h-[20px] mb-[24px] mt-[24px] relative">
                <div className="absolute w-full h-[1px] bg-fifth top-[50%] -translate-y-[50%]" />
                <div
                  className={`absolute z-[1] justify-center items-center w-full start-0 -top-[4px] flex`}
                >
                  <div className="px-[16px]">{t('or', 'or')}</div>
                </div>
              </div>
            )}
            <div className="flex flex-col gap-[12px]">
              <div className="text-textColor">
                {!isAfterProvider && (
                  <>
                    <Input
                      label="Email"
                      translationKey="label_email"
                      {...form.register('email')}
                      type="email"
                      placeholder={t('email_address', 'Email Address')}
                    />
                    <Input
                      label="Password"
                      translationKey="label_password"
                      {...form.register('password')}
                      autoComplete="off"
                      type="password"
                      placeholder={t('label_password', 'Password')}
                    />
                  </>
                )}
                <Input
                  label="Company"
                  translationKey="label_company"
                  {...form.register('company')}
                  autoComplete="off"
                  type="text"
                  placeholder={t('label_company', 'Company')}
                />
              </div>
              <div className={clsx('text-[12px]')}>
                {t(
                  'by_registering_you_agree_to_our',
                  'By registering you agree to our'
                )}
                &nbsp;
                <a
                  href={`https://postiz.com/terms`}
                  className="underline hover:font-bold"
                  rel="nofollow"
                >
                  {t('terms_of_service', 'Terms of Service')}
                </a>
                &nbsp;
                {t('and', 'and')}&nbsp;
                <a
                  href={`https://postiz.com/privacy`}
                  rel="nofollow"
                  className="underline hover:font-bold"
                >
                  {t('privacy_policy', 'Privacy Policy')}
                </a>
                &nbsp;
              </div>
              <div className="text-center mt-6">
                <div className="w-full flex">
                  <Button
                    type="submit"
                    className="flex-1 rounded-[10px] !h-[52px]"
                    loading={loading}
                  >
                    {t('create_account', 'Create Account')}
                  </Button>
                </div>
                <p className="mt-4 text-sm">
                  {t('already_have_an_account', 'Already Have An Account?')}
                  &nbsp;
                  <Link
                    href="/auth/login"
                    className="underline  cursor-pointer"
                  >
                    {t('sign_in', 'Sign In')}
                  </Link>
                </p>
              </div>
            </div>
          </div>
        </div>
      </form>
    </FormProvider>
  );
}
